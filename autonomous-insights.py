#!/usr/bin/env python3
"""
Autonomous QZero Insights Analyzer - Hourly Task
===========================

Purpose: Analyze recently generated insights and detect meaningful patterns
Good for: QZero project intelligence, anomaly detection research, skill building

Criteria met:
- bueno para la humanidad: Improves anomaly detection capabilities for network security
- bueno para mí: Contributes to learning about pattern recognition in network traffic
- bueno para ti: Makes the project smarter through automated analysis

How it works:
1. Scans insights/ directory for recent files
2. Analyzes if new anomalies were detected
3. Checks for patterns in anomalies over time
4. Generates insights summary
5. Commits significant findings to git
"""

import os
import sys
import json
import re
from datetime import datetime, timedelta
from pathlib import Path
import subprocess
import glob

# Add src to path
sys.path.insert(0, str(Path(__file__).parent / "src"))


def scan_insights(insights_dir, hours_back=2):
    """Scan for recently generated insights"""
    cutoff = datetime.now() - timedelta(hours=hours_back)
    recent_files = []

    for file_path in glob.glob(str(insights_dir / "*.json")):
        mtime = datetime.fromtimestamp(Path(file_path).stat().st_mtime)
        if mtime >= cutoff:
            recent_files.append(file_path)

    return sorted(recent_files, reverse=True)


def analyze_anomalies(insights_files):
    """Analyze anomaly detection results"""
    anomalies = []
    total_detections = 0

    for file_path in insights_files:
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)

            if 'anomalies' in data and data['anomalies']:
                anomalies.extend(data['anomalies'])
                total_detections += len(data['anomalies'])

        except Exception as e:
            continue

    return anomalies, total_detections


def detect_patterns(anomalies):
    """Detect patterns in anomalies"""
    patterns = {
        'by_type': {},
        'by_time': {},
        'by_source': {}
    }

    for anomaly in anomalies:
        # Type pattern
        anomaly_type = anomaly.get('type', 'unknown')
        patterns['by_type'][anomaly_type] = patterns['by_type'].get(anomaly_type, 0) + 1

        # Time pattern
        time_str = anomaly.get('timestamp', '')
        if time_str:
            try:
                dt = datetime.fromisoformat(time_str.replace('Z', '+00:00'))
                hour = dt.hour
                patterns['by_time'][hour] = patterns['by_time'].get(hour, 0) + 1
            except:
                pass

        # Source pattern
        source = anomaly.get('source', 'unknown')
        patterns['by_source'][source] = patterns['by_source'].get(source, 0) + 1

    return patterns


def generate_summary(anomalies, patterns, total_detections):
    """Generate insights summary"""
    timestamp = datetime.now().isoformat()

    summary = f"""# QZero Insights Summary - {datetime.now().strftime('%Y-%m-%d %H:%M')}

## Summary
- **Total Anomalies Detected**: {total_detections}
- **Analysis Window**: Last 2 hours
- **Unique Anomaly Types**: {len(patterns['by_type'])}
- **Unique Sources**: {len(patterns['by_source'])}

## Anomalies by Type
"""
    for type_name, count in sorted(patterns['by_type'].items(), key=lambda x: x[1], reverse=True):
        summary += f"- **{type_name}**: {count}\n"

    summary += f"""

## Anomalies by Hour
"""
    for hour, count in sorted(patterns['by_time'].items(), key=lambda x: x[0]):
        summary += f"- **{hour}:00**: {count}\n"

    summary += f"""

## Anomalies by Source
"""
    for source, count in sorted(patterns['by_source'].items(), key=lambda x: x[1], reverse=True):
        summary += f"- **{source}**: {count}\n"

    summary += f"""

## Analysis Notes
"""
    if total_detections > 10:
        summary += "- **High activity detected** - May indicate ongoing scanning or attack attempt"
    elif total_detections > 5:
        summary += "- **Moderate activity** - Worth monitoring"
    else:
        summary += "- **Normal activity levels** - No immediate concern"

    if patterns['by_time']:
        peak_hour = max(patterns['by_time'].items(), key=lambda x: x[1])
        summary += f"\n- **Peak hour**: {peak_hour[0]:02d}:00"

    summary += f"""

---
*Auto-generated by autonomous-insights.py at {timestamp}*

*This analysis helps improve anomaly detection models by identifying real-world patterns*
"""

    return summary


def check_for_changes(summary_text):
    """Check if summary has meaningful changes"""
    # Simple heuristic: check if anomaly count changed significantly
    anomaly_count = summary_text.count("- **Anomalies Detected**")

    # Check if there are new anomalies
    has_new = "High activity detected" in summary_text or "Moderate activity" in summary_text

    return has_new or anomaly_count > 0


def commit_if_needed(project_dir, summary_file, summary_text):
    """Commit changes if meaningful"""
    try:
        # Check git status
        result = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=project_dir,
            capture_output=True,
            text=True
        )

        changed = [line.split()[-1] for line in result.stdout.strip().split("\n") if line.strip()]

        if changed and check_for_changes(summary_text):
            timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
            msg = f"[insights] Update: {timestamp}"

            subprocess.run(
                ["git", "add", str(summary_file)],
                cwd=project_dir,
                capture_output=True
            )

            subprocess.run(
                ["git", "commit", "-m", msg],
                cwd=project_dir,
                capture_output=True
            )

            print(f"✓ Changes committed: {msg}")
            return True

    except Exception as e:
        print(f"✗ Commit error: {e}")

    return False


def main():
    print(f"\n{'='*60}")
    print(" autonomous-insights.py - QZero Insights Analyzer")
    print(f"{'='*60}")
    print(f" Started: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"{'='*60}\n")

    project_dir = Path(__file__).parent
    insights_dir = project_dir / "insights"

    # Scan for recent insights
    insights_files = scan_insights(insights_dir)
    print(f"✓ Found {len(insights_files)} recent insight files")

    if not insights_files:
        print("✓ No recent insights to analyze")
        return

    # Analyze anomalies
    anomalies, total_detections = analyze_anomalies(insights_files)
    print(f"✓ Analyzed {total_detections} anomalies")

    # Detect patterns
    patterns = detect_patterns(anomalies)
    print(f"✓ Detected {len(patterns['by_type'])} anomaly types")

    # Generate summary
    summary = generate_summary(anomalies, patterns, total_detections)
    print(f"✓ Generated insights summary")

    # Save summary
    summary_file = project_dir / "reports" / f"insights-summary-{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
    summary_file.parent.mkdir(exist_ok=True)

    with open(summary_file, 'w') as f:
        f.write(summary)

    print(f"✓ Saved to: {summary_file}")

    # Commit if meaningful changes
    if commit_if_needed(project_dir, summary_file, summary):
        print(f"✓ Changes committed to git")

    print(f"\n{'='*60}")
    print(f" Analysis completed: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    main()